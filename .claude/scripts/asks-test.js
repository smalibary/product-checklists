// Checks the asks hook (hooks/asks.js) against Salem's 2026-11-14 cases, in a scratch project. Run: node .claude/scripts/asks-test.js .claude/hooks
const fs = require('fs'), path = require('path'), os = require('os'), { spawnSync } = require('child_process');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'asks-'));
fs.mkdirSync(path.join(dir, '.claude', 'hooks'), { recursive: true });
fs.copyFileSync(path.join(process.argv[2], 'asks.js'), path.join(dir, '.claude', 'hooks', 'asks.js'));
const T = path.join(dir, 't.jsonl');
fs.writeFileSync(T, '');
const env = { ...process.env, CLAUDE_PROJECT_DIR: dir };
const hook = (mode, input) => spawnSync('node', ['.claude/hooks/asks.js', mode], { cwd: dir, env, input: JSON.stringify(input), encoding: 'utf8' });
const cli = (...a) => spawnSync('node', ['.claude/hooks/asks.js', ...a], { cwd: dir, env, encoding: 'utf8' }).stdout.trim();
const tool = () => fs.appendFileSync(T, JSON.stringify({ type: 'assistant', message: { content: [{ type: 'tool_use', name: 'Edit' }] } }) + '\n');
const said = text => fs.appendFileSync(T, JSON.stringify({ type: 'user', timestamp: new Date().toISOString(), message: { content: text } }) + '\n');
const stop = (active) => { const r = hook('stop', { transcript_path: T, stop_hook_active: !!active }); return r.stdout.includes('"block"'); };
let fails = 0;
const check = (name, ok) => { console.log((ok ? 'PASS ' : 'FAIL ') + name); if (!ok) fails++; };

let r = hook('prompt', { prompt: 'Continue working on the rest of screens' }); said('Continue working on the rest of screens');
check('1. his message is recorded as an ask', r.stdout.includes('ask #1'));
cli('set', '1', 'standing', '3 of 9 screens'); cli('parts', '1', 'Home|Tasks|Me');
r = hook('prompt', { prompt: 'the app turns sideways, lock it upright' }); said('the app turns sideways, lock it upright');
check('2. a new issue reminds Claude of the ongoing order', r.stdout.includes('#1 [standing]'));
tool(); cli('set', '2', 'done', 'locked upright');
check('3. stopping after the fix is refused while the screens order is open', stop(false));
tool();
check('4. after more work, stopping again is still refused', stop(true));
check('5. stopping twice with no work between is let through (never trapped)', !stop(true));
said('also the home title is cut off');
cli('tick', '1', 'Home|Tasks|Me'); cli('set', '1', 'done', '9 of 9 screens');
check('6. a message sent mid-turn is picked up and blocks the stop', stop(false) && cli('list').includes('home title'));
const id = cli('list').match(/#(\d+)/)[1];
cli('set', id, 'done', 'fixed');
check('7. the same message is not recorded twice', JSON.parse(fs.readFileSync(path.join(dir, '.claude/state/asks.json'))).asks.length === 3);
check('8. with everything sorted, the stop goes through', !stop(false));
r = hook('prompt', { prompt: '<command-message>x</command-message>\n<command-name>/project-setup</command-name>\n<command-args>record all my comments</command-args>' });
check('9. a slash command keeps what he wrote after it', cli('list').includes('/project-setup: record all my comments'));
cli('set', '4', 'waiting', 'question on the board');
check('10. waiting on his answer does not block', !stop(false));
r = hook('prompt', { prompt: 'polish every screen' });
check('11. a many-things ask asks for its parts', r.stdout.includes('parts 5'));
const err = (...a) => spawnSync('node', ['.claude/hooks/asks.js', ...a], { cwd: dir, env, encoding: 'utf8' });
check('12. done without parts is refused', err('set', '5', 'done', 'every screen polished').status === 1);
cli('parts', '5', 'Home|Wardrobe|Account');
cli('tick', '5', 'Home|Wardrobe');
check('13. done with a part left is refused (12 of 19 case)', err('set', '5', 'done', 'all polished').status === 1);
check('14. the list shows what is left', cli('list').includes('2 of 3 parts done; left: Account'));
check('15. ticking a part that does not exist is refused', err('tick', '5', 'Login').status === 1);
cli('tick', '5', 'account');
check('16. with every part ticked, done goes through', err('set', '5', 'done', '3 of 3').status === 0);
check('17. a single-thing ask still closes without parts', err('set', '2', 'done', 'answered').status === 0);
console.log(fails ? fails + ' failed' : 'all passed');
fs.rmSync(dir, { recursive: true, force: true });
